import { clock, durationOf, endOf, roomLocation, yearOf } from '../core.js';
import { screeningUrl } from '../story.js';
import { calendarState, zonedStart } from '../discovery-time.js';

export const origin = 'https://vivaelcine.cl';
export const escapeHtml = value => String(value ?? '').replace(/[&<>"']/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[char]);
const esc = escapeHtml;
export const editionPath = festival => `/festivales/${festival.id}/`;
export const dayPath = (festival, date) => `${editionPath(festival)}${date}/`;
export const screeningPath = event => `/funciones/${event.id}/`;
export const dateLabel = date => new Intl.DateTimeFormat('es-CL', {
  weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC',
}).format(new Date(`${date}T12:00:00Z`));
const link = (url, label, className = '') => `<a${className ? ` class="${className}"` : ''} href="${esc(url)}">${esc(label)}</a>`;
const sorted = events => [...events].sort((a, b) => a.date.localeCompare(b.date) || a.start - b.start || a.id.localeCompare(b.id));

