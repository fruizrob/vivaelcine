function status(first, last, asOf) {
  return `<p class="status">${esc(calendarState(first, last, asOf))} · al ${esc(asOf)}</p>`;
}

function provenance(festival, source, event) {
  const checked = event?.sourceCheckedAt ?? festival.sourceCheckedAt ?? null;
  return `<details class="provenance"><summary>Fuentes y vigencia</summary>
    <p>${link(source.scheduleUrl, 'Fuente de horarios')}${source.recordUrl ? ` · ${link(source.recordUrl, 'Registro de procedencia')}` : ''}</p>
    <p>Fuente consultada: <time datetime="${source.retrievedOn}">${esc(dateLabel(source.retrievedOn))}</time> (precisión de día).</p>
    <p>Última comprobación de esta función: ${checked ? `<time datetime="${esc(checked)}">${esc(checked)}</time>` : 'sin fecha registrada'}. Fecha de cambio material de horarios: ${esc(event?.scheduleChangedAt ?? 'sin registro')}.</p>
    <p>Generar estas páginas no vuelve a comprobar las fuentes. Consulta al organizador por cambios, cupos, subtítulos y accesibilidad. Los enlaces de entradas no indican inventario en vivo.</p>
  </details>`;
}

function rows(festival, events) {
  return `<ol class="screenings">${sorted(events).map(event => {
    const film = festival.films[event.filmId];
    const room = festival.rooms.find(room => room.id === event.roomId);
    const duration = durationOf(event, festival.films);
    return `<li><time datetime="${zonedStart(event.date, event.start, festival.timeZone)}">${clock(event.start)}</time><div>${link(screeningPath(event), event.title || film.title)}<p>${esc(roomLocation(room))} · ${duration === null ? 'Duración no publicada' : `${duration} min`}</p></div></li>`;
  }).join('\n')}</ol>`;
}

function films(festival, event, film) {
  const title = event.title || film.title;
  const year = yearOf(event, film);
  const yearSource = event.yearSource || film.yearSource;
  const details = [esc(film.director), year && (yearSource ? link(yearSource, year) : esc(year)), esc(film.countries)].filter(Boolean).join(' · ');
  const alternate = !event.title && film.originalTitle && film.originalTitle.toLowerCase() !== title.toLowerCase();
  return `<p>${details}</p>
    ${event.title ? `<p>Obra: ${esc(film.title)}</p>` : ''}
    ${alternate ? `<p>Título original: ${esc(film.originalTitle)}</p>` : ''}
    ${film.alias ? `<p>También conocida como: ${esc(film.alias)}</p>` : ''}
    ${film.components ? `<section aria-labelledby="films-heading"><h2 id="films-heading">Películas del programa</h2><ul class="films">${film.components.map(component => `<li>${link(component.source, component.title)}${yearOf({}, component) ? ` (${yearOf({}, component)})` : ''}${component.duration ? ` · ${component.duration} min` : ''}${component.director ? `<p>${esc(component.director)}</p>` : ''}${component.originalTitle && component.originalTitle !== component.title ? `<p>${esc(component.originalTitle)}</p>` : ''}</li>`).join('')}</ul></section>` : ''}`;
}

export function buildPages(festivals, sources, asOf) {
  const pages = new Map();
  for (const festival of festivals) {
    const events = sorted(festival.events);
    const first = events[0].date;
    const last = events.at(-1).date;
    const source = sources[festival.id];
    const name = `${festival.name} · ${first.slice(0, 4)}`;
    const days = festival.days.map(day => `<li>${link(dayPath(festival, day.date), dateLabel(day.date))} <span>${events.filter(event => event.date === day.date).length} funciones</span></li>`).join('\n');
    pages.set(editionPath(festival), frame(editionPath(festival), `Programación de ${name}`,
      `${festival.name}: ${events.length} funciones registradas del ${first} al ${last} en Santiago. Horarios, salas y fuentes por día.`,
      `<h1>Programación de ${esc(name)}</h1>${status(first, last, asOf)}
      <p>Funciones registradas del <time datetime="${first}">${esc(dateLabel(first))}</time> al <time datetime="${last}">${esc(dateLabel(last))}</time>. Estos límites describen nuestra programación; no una confirmación independiente de apertura y clausura.</p>
      <p>${link(`/?festival=${festival.id}`, 'Ver en la agenda', 'button')}</p>
      <nav aria-label="Días de programación"><ul class="days">${days}</ul></nav>
      ${provenance(festival, source)}`, asOf));

    for (const day of festival.days) {
      const path = dayPath(festival, day.date);
      pages.set(path, frame(path, `${festival.name}: ${dateLabel(day.date)}`,
        `Funciones de ${festival.name} el ${dateLabel(day.date)} en Santiago. Horarios locales, salas y enlaces a cada función.`,
        `<nav aria-label="Ruta">${link(editionPath(festival), name)}</nav>
        <h1>${esc(dateLabel(day.date))}</h1><p>${esc(name)} · Horarios en ${esc(festival.timeZone)}</p>${status(day.date, day.date, asOf)}
        <p>${link(`/?festival=${festival.id}&dia=${day.date}`, 'Ver día en la agenda', 'button')}</p>
        ${rows(festival, events.filter(event => event.date === day.date))}
        <nav aria-label="Otros días"><ul class="days">${days}</ul></nav>${provenance(festival, source)}`, asOf));
    }

    for (const event of events) {
      const film = festival.films[event.filmId];
      const room = festival.rooms.find(room => room.id === event.roomId);
      const title = event.title || film.title;
      const duration = durationOf(event, festival.films);
      const end = endOf(event, festival.films);
      const path = screeningPath(event);
      const official = event.source || film.source;
      const ticket = event.ticketUrl || film.ticketUrl;
      const other = events.filter(other => other.filmId === event.filmId && other.id !== event.id);
      const description = `${title} en ${festival.name}: ${dateLabel(event.date)}, ${clock(event.start)}, ${roomLocation(room)}. ${duration === null ? 'Duración no publicada.' : `${duration} min.`}`;
      const eventSource = { ...source, scheduleUrl: festival.programUrl ? `${origin}/assets/programacion-sanfic22.pdf#page=${event.sourcePage}` : official };
      pages.set(path, frame(path, `${title}: ${event.date} ${clock(event.start)} · ${festival.name}`, description,
        `<nav aria-label="Ruta">${link(editionPath(festival), name)} / ${link(dayPath(festival, event.date), dateLabel(event.date))}</nav>
        <h1>${esc(title)}</h1>${status(event.date, event.date, asOf)}
        <dl><div><dt>Fecha y hora</dt><dd><time datetime="${zonedStart(event.date, event.start, festival.timeZone)}">${esc(dateLabel(event.date))}, ${clock(event.start)}</time> · ${esc(festival.timeZone)}</dd></div>
        <div><dt>Sede y sala</dt><dd>${esc(roomLocation(room))}</dd></div>
        <div><dt>Duración</dt><dd>${duration === null ? 'No publicada para esta función' : `${duration} min${film.durationKind === 'sum' ? ' (suma de cortometrajes)' : ''}`}</dd></div>
        <div><dt>Final</dt><dd>${end === null ? 'Desconocido' : `${clock(end, true)} estimado por metraje; excluye presentaciones y conversatorios`}</dd></div>
        ${film.free === true ? '<div><dt>Entrada</dt><dd>Gratuita según la fuente; cupos sin confirmar</dd></div>' : ''}</dl>
        <p class="actions">${link(ticket || official, ticket ? 'Entradas' : 'Ficha oficial', 'button')} ${link(screeningUrl(festival, event, `${origin}/`).slice(origin.length), 'Ver en la agenda')}</p>
        <p>Fecha programada según la fuente consultada; confirma cambios y condiciones con el organizador.</p>
        ${event.note ? `<p>${esc(event.note)}</p>` : ''}${film.note ? `<p>${esc(film.note)}</p>` : ''}
        ${films(festival, event, film)}
        <p>${link(official, film.components ? 'Programa en la fuente' : 'Ficha en la fuente')}${event.durationSource ? ` · ${link(event.durationSource, 'Fuente del metraje de esta parte')}` : ''}</p>
        ${other.length ? `<section><h2>${event.title ? 'Otras partes o funciones de la obra' : 'Otras funciones'}</h2><ul class="alternatives">${other.map(other => `<li>${link(screeningPath(other), `${other.title || title} · ${dateLabel(other.date)}, ${clock(other.start)} · ${roomLocation(festival.rooms.find(room => room.id === other.roomId))}`)}</li>`).join('')}</ul></section>` : ''}
        ${provenance(festival, eventSource, event)}`, asOf));
    }
  }
  return pages;
}

export function sitemap(pages) {
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${['/', ...pages.keys()].map(path => `  <url><loc>${origin}${path}</loc></url>`).join('\n')}\n</urlset>\n`;
}
