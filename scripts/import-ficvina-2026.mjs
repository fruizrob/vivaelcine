import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile, rename } from 'node:fs/promises';

// Offline only: the source manifest is a visual transcription of an image-only PDF.
const root = new URL('../', import.meta.url);
const source = JSON.parse(await readFile(new URL('assets/ficvina-2026-sources.json', root)));
const pdf = await readFile(new URL('assets/programacion-ficvina-2026.pdf', root));
assert.equal(createHash('sha256').update(pdf).digest('hex'), source.sha256, 'Source PDF changed; review the transcription first.');
assert.equal(source.events.length, 42);
assert.equal(new Set(source.events.map(event => event.id)).size, 42);
for (const event of source.events) {
  assert.ok(source.films[event.filmId], event.id);
  assert.ok(source.sections[source.films[event.filmId].section], event.id);
  assert.ok(source.rooms.some(room => room.id === event.roomId && room.venueId === event.venueId), event.id);
  assert.ok(Number.isInteger(event.start) && event.start >= 0 && event.start < 1440, event.id);
}
const shortDays = ['DOM', 'LUN', 'MAR', 'MIÉ', 'JUE', 'VIE', 'SÁB'];
const labels = ['Domingo', 'Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes', 'Sábado'];
const days = [...new Set(source.events.map(event => event.date))].sort().map(date => {
  const day = new Date(`${date}T12:00:00Z`);
  return { date, short: shortDays[day.getUTCDay()], label: labels[day.getUTCDay()], number: day.getUTCDate() };
});
const schedule = {
  id: 'ficvina-2026', name: 'FICVIÑA 38', edition: 38, year: 2026,
  city: 'Viña del Mar',
  updated: source.collected, timeZone: 'America/Santiago',
  sourceUrl: 'https://cinevina.cl/', programUrl: './assets/programacion-ficvina-2026.pdf',
  festivalDates: { start: '2026-11-23', end: '2026-11-28' },
  dateRange: '20–28 nov 2026', dateRangeKind: 'observed-screenings-including-previews',
  days, sections: source.sections, rooms: source.rooms, films: source.films, events: source.events,
};
const compact = value => JSON.stringify(value);
const lines = ['// Generated by node scripts/import-ficvina-2026.mjs; edit the source manifest instead.', 'export default {'];
for (const [key, value] of Object.entries(schedule)) {
  if (Array.isArray(value)) lines.push(`${compact(key)}:[`, ...value.map(row => `${compact(row)},`), '],');
  else if (key === 'films' || key === 'sections') lines.push(`${compact(key)}:{`, ...Object.entries(value).map(([id, row]) => `${compact(id)}:${compact(row)},`), '},');
  else lines.push(`${compact(key)}:${compact(value)},`);
}
lines.push('};', '');
const output = new URL('data/ficvina-2026.js', root);
const temporary = new URL(`data/ficvina-2026.js.${process.pid}.tmp`, root);
await writeFile(temporary, lines.join('\n'));
await rename(temporary, output);
console.log(`FICVIÑA 38: ${source.events.length} screenings across ${days.length} dates.`);
