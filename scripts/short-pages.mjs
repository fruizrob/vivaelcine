import { createHash } from 'node:crypto';
import { clock, durationOf, roomLocation } from '../core.js';
import { agendaScreeningUrl } from '../screening-links.js';
import { calendarState } from '../discovery-time.js';
import { dateLabel, editionPath, screeningPath, frame, escapeHtml as esc, origin } from './discovery-pages.mjs';

export function updateLinks(festivals, previous) {
  const entries = structuredClone(previous);
  const identities = new Map();
  for (const [code, entry] of Object.entries(entries)) {
    if (!/^[a-f0-9]{8}$/.test(code) || !entry.festivalId || !entry.eventId || !entry.title) {
      throw new Error(`Invalid short-link entry: ${code}`);
    }
    const key = `${entry.festivalId}/${entry.eventId}`;
    if (identities.has(key)) throw new Error(`Duplicate short-link identity: ${key}`);
    identities.set(key, code);
  }
  for (const festival of festivals) {
    for (const event of festival.events) {
      const key = `${festival.id}/${event.id}`;
      let code = identities.get(key);
      if (!code) {
        code = createHash('sha256').update(key).digest('hex').slice(0, 8);
        if (entries[code]) throw new Error(`Short-link collision: ${code}; allocate a distinct unused code in the registry.`);
        identities.set(key, code);
      }
      entries[code] = { festivalId: festival.id, eventId: event.id, title: event.title || festival.films[event.filmId].title };
    }
  }
  return Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)));
}

export const serializeLinks = entries => '// Append-only public screening identities. Generated by npm run generate:pages.\n'
  + `export default {\n${Object.entries(entries).map(([code, entry]) => `  ${JSON.stringify(code)}: ${JSON.stringify(entry)},`).join('\n')}\n};\n`;

export function buildShortPages(festivals, entries, asOf) {
  const pages = new Map();
  for (const [code, entry] of Object.entries(entries)) {
    const path = `/s/${code}/`;
    const festival = festivals.find(item => item.id === entry.festivalId);
    const event = festival?.events.find(item => item.id === entry.eventId);
    if (!event) {
      pages.set(path, frame(path, entry.title, 'Esta función ya no aparece en la programación publicada.',
        `<h1>${esc(entry.title)}</h1><p>Esta función ya no aparece en la programación publicada. Consulta al organizador por cambios.</p>
        <p><a class="button" href="${esc(festival ? editionPath(festival) : '/')}">${festival ? 'Ver programación del festival' : 'Abrir agenda'}</a></p>`, asOf, true));
      continue;
    }
    const film = festival.films[event.filmId];
    const title = event.title || film.title;
    const room = roomLocation(festival.rooms.find(item => item.id === event.roomId));
    const duration = durationOf(event, festival.films);
    const description = `${festival.name} · ${dateLabel(event.date)}, ${clock(event.start)} · ${room}.`;
    const agenda = agendaScreeningUrl(festival, event, `${origin}/`).slice(origin.length);
    const html = frame(path, `${title} · ${festival.name} · ${event.date} ${clock(event.start)}`, description,
      `<p>${esc(festival.name)}</p><h1>${esc(title)}</h1>
      <p class="status">${esc(calendarState(event.date, event.date, asOf))} · al ${esc(asOf)}</p>
      <p>${esc(dateLabel(event.date))} · ${clock(event.start)} · ${esc(festival.timeZone)}</p>
      <p>${esc(room)} · ${duration === null ? 'Duración no publicada' : `${duration} min`}</p>
      <p class="actions"><a class="button" href="${esc(agenda)}">Ver en la agenda</a><a href="${esc(screeningPath(event))}">Detalles y fuentes</a></p>
      ${film.components ? `<section><h2>Películas del programa</h2><ul>${film.components.map(component => `<li>${esc(component.title)}</li>`).join('')}</ul></section>` : ''}
      ${[...new Set([event.note, film.note].filter(Boolean))].map(note => `<p>${esc(note)}</p>`).join('')}`, asOf, true);
    pages.set(path, html.replace('</head>', `  <script src="/open-screening.js?v=20261112-direct" data-screening-url="${esc(agenda)}"></script>\n</head>`));
  }
  return pages;
}

export function notFoundPage(asOf) {
  return frame('/404.html', 'Página no encontrada', 'No encontramos esta página en Viva el Cine.',
    '<h1>No encontramos esta página</h1><p>Comprueba el enlace o busca la función en la agenda.</p><p><a class="button" href="/">Abrir agenda</a></p>', asOf, true)
    .replace('  <link rel="canonical"', '  <meta name="robots" content="noindex">\n  <link rel="canonical"');
}
